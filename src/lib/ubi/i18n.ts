export type I18nKey = keyof typeof dict.ja;

export type Copy = { ja: string; en: string; zh?: string; fr?: string };

export function detectLang(): Lang {
  if (typeof navigator === "undefined") return "ja";
  const raw = (navigator.language || "ja").toLowerCase();
  if (raw.startsWith("zh")) return "zh";
  if (raw.startsWith("en")) return "en";
  if (raw.startsWith("fr")) return "fr";
  return "ja";
}

export function t(lang: Lang, key: I18nKey) {
  return dict[lang][key] ?? dict.ja[key];
}

export function tx(lang: Lang, parts: Copy) {
  if (lang === "en") return parts.en;
  if (lang === "fr") return parts.fr ?? parts.en;
  if (lang === "zh") return parts.zh ?? parts.ja;
  return parts.ja;
}
